// Real pointer/keyboard acceptance for the shared sketch workspace.
import {isDeepStrictEqual} from 'node:util';
import {readFileSync, existsSync} from 'node:fs';
export async function sketchScenario({control,state,waitFor,send,evaluate,sleep,record,screenshot,pressKey,click,path,out,chooseFile}) {
  const assert=(condition,message)=>{if(!condition)throw Error(message);};
  const model=s=>s.workspace?.sketch?.model;
  const button=async label=>{const r=(await state()).controls[label];assert(r,`Missing ${label}`);await click((r[0]+r[2])/2,(r[1]+r[3])/2);await sleep(100);};
  const xy=async(x,y)=>{const s=await state(),r=s.controls['Sketch canvas'],v=s.sketch;return [(r[0]+r[2])/2+(x-v.center[0])*v.scale,(r[1]+r[3])/2-(y-v.center[1])*v.scale];};
  const point=async(x,y)=>{await click(...await xy(x,y));await sleep(100);};
  const draw=async(tool,points)=>{await button(`Sketch ${tool}`);for(const p of points)await point(...p);};
  await control('File');await control('New job');await waitFor(s=>s.job&&!s.active,'empty job');
  const original=await state();
  await button('New sketch');await waitFor(s=>s.sketch,'sketch workspace');
  await draw('Rectangle',[[10,10],[80,70]]);
  await draw('Circle',[[30,30],[40,30]]);
  await draw('Arc',[[82,10],[95,20],[82,30]]);
  await draw('Line',[[10,80],[70,80]]);
  await draw('Polyline',[[85,50],[95,50],[95,65],[85,65],[85,50]]);
  await button('Sketch construction');await draw('Line',[[15,15],[70,65]]);await button('Sketch construction');
  await draw('Point',[[20,20]]);
  let s=await state();assert(model(s).entities.length===13,'all drawing tools publish entities');assert(model(s).constraints.length===4,'only the rectangle should introduce constraints');
  assert(model(s).constraints.filter(c=>c.definition.kind==='horizontal').length===2&&model(s).constraints.filter(c=>c.definition.kind==='vertical').length===2,'rectangle must retain its shape');
  assert(isDeepStrictEqual(s.job,original.job),'local draft mutated the job');
  record('seven drawing tools; connected wires; construction excluded from machining',s.sketch);
  await button('Sketch Select');await point(30,40);
  const circle=model(await state()).entities.find(e=>e.geometry.kind==='circle');
  const start=await xy(30,40),end=await xy(35,40);
  await send('Input.dispatchMouseEvent',{type:'mouseMoved',x:start[0],y:start[1]});
  await send('Input.dispatchMouseEvent',{type:'mousePressed',x:start[0],y:start[1],button:'left',clickCount:1});
  for(let i=1;i<=5;i++){await send('Input.dispatchMouseEvent',{type:'mouseMoved',x:start[0]+(end[0]-start[0])*i/5,y:end[1],button:'left',buttons:1});await sleep(80);}
  await send('Input.dispatchMouseEvent',{type:'mouseReleased',x:end[0],y:end[1],button:'left',clickCount:1});await sleep(180);
  s=await waitFor(s=>!s.sketch.solving&&!s.sketch.pending,'solved free drag');assert(Math.abs(model(s).entities.find(e=>e.id===circle.id).geometry.center.x-35)<1e-3,'drag did not move circle');
  await pressKey('z','KeyZ',2);s=await state();assert(model(s).entities.find(e=>e.id===circle.id).geometry.center.x===30,'local undo failed');
  await pressKey('y','KeyY',2);s=await state();assert(Math.abs(model(s).entities.find(e=>e.id===circle.id).geometry.center.x-35)<1e-3,'local redo failed');
  assert(s.undo===original.undo,'local history leaked into job history');
  await screenshot('sketch-drawing.png');
  await draw('Circle',[[79,40],[84,40]]);await button('Apply sketch');s=await state();assert(s.sketch&&s.sketch.message,'crossing region should keep invalid draft open');
  await button('Sketch undo');await button('Apply sketch');
  s=await waitFor(s=>!s.sketch&&!s.active&&s.job.artworks.length===1,'applied sketch');
  assert(isDeepStrictEqual(s.job.stock,original.job.stock),'Apply changed stock');
  assert(s.undo===original.undo+1,'Apply is not one job transaction');
  const applied=structuredClone(s.job.artworks);
  record('validated Apply is one transaction and keeps stock',s.job);
  await control('Add operation');await control('Add Profile — profile-1');await waitFor(s=>!s.active&&s.job.kind==='profile','profile operation');
  await control('Select all profile contours');await waitFor(s=>!s.active&&s.job.contours===3,'sketch contours selected for machining');
  record('published sketch geometry can be selected by a CAM operation',(await state()).job);
  await control('Artwork');
  await evaluate('globalThis.showSaveFilePicker=undefined');
  await control('Save job');await waitFor(s=>s.status.includes('Download requested'),'saved sketch download');
  const file=path.join(out,'carving.gui2.job.json');
  for(let i=0;i<40&&!existsSync(file);i++)await sleep(250);
  assert(existsSync(file),'saved job missing');
  const saved=JSON.parse(readFileSync(file,'utf8'));assert(saved.artwork[0].content.kind==='sketch','saved model is not a sketch');
  await button('Edit sketch');await waitFor(s=>s.sketch,'edit sketch');
  await draw('Circle',[[50,30],[55,30]]);await button('Cancel sketch');
  s=await state();assert(isDeepStrictEqual(s.job.artworks,applied),'Cancel changed artwork');
  await button('Edit sketch');await waitFor(s=>s.sketch,'recovery draft');
  await draw('Point',[[55,50]]);const recovered=model(await state());await sleep(2200);
  await send('Page.reload',{ignoreCache:true});await waitFor(s=>s.controls?.['Restore draft'],'local recovery offer');await control('Restore draft');
  s=await waitFor(s=>s.sketch,'restored sketch');assert(isDeepStrictEqual(model(s),recovered),'recovery lost local model');
  await button('Cancel sketch');await control('File');await chooseFile('Open job',file);
  s=await waitFor(s=>!s.active&&s.job?.artworks?.length===1&&!s.sketch,'saved sketch reopened');
  assert(isDeepStrictEqual(s.job.artworks,applied),'save/open changed artwork');
  await control('Artwork');
  await button('Edit sketch');
  await send('Emulation.setDeviceMetricsOverride',{width:640,height:400,deviceScaleFactor:1,mobile:false});await sleep(300);
  s=await state();for(const label of ['Apply sketch','Cancel sketch','Sketch canvas']){const r=s.controls[label];assert(r&&r[0]>=0&&r[2]<=640&&r[3]<=400,`compact layout clipped ${label}`);}
  await screenshot('sketch-compact.png');
  await send('Emulation.setDeviceMetricsOverride',{width:1280,height:800,deviceScaleFactor:1,mobile:false});await sleep(200);
  await button('Cancel sketch');await screenshot('sketch-applied.png');
  record('save/open, Edit/Cancel, recovery, and compact workspace',await state());
}

// V2 shell acceptance: all mutations travel through the visible controls.
import {isDeepStrictEqual} from 'node:util';
export async function shellScenario({control,state,waitFor,send,evaluate,sleep,record,screenshot,readFileSync,pressKey}) {
  const base=JSON.parse(readFileSync('fixtures/gui4/lettering.job.json','utf8'));
  const drop=async job=>{
    await evaluate(`(()=>{const t=new DataTransfer();t.items.add(new File([${JSON.stringify(JSON.stringify(job))}],'shell-review.job.json',{type:'application/json'}));document.getElementById('cam').dispatchEvent(new DragEvent('drop',{dataTransfer:t,bubbles:true,cancelable:true}));})()`);
    await waitFor(s=>s.job?.name===job.name&&s.job.operations.length===job.operations.length&&!s.active,'shell fixture');
  };
  const job=structuredClone(base);
  job.name='A deliberately long document name for checking the compact machining workspace and its retained document status.svg';
  job.operations=Array.from({length:12},(_,i)=>({...structuredClone(base.operations[0]),id:`row-${i+1}`,name:'Duplicate operation name'}));
  await send('Emulation.setDeviceMetricsOverride',{width:1280,height:800,deviceScaleFactor:1,mobile:false});
  await drop(job);await sleep(300);
  const manage=(await state()).controls['Job tools'];
  await control('Operation row row-12');
  await waitFor(s=>s.job.selectedOperation==='row-12','last of twelve operations');
  if(JSON.stringify(manage)!==JSON.stringify((await state()).controls['Job tools']))throw Error('Job tools moved with the operation scroll');
  await screenshot('shell-twelve-operations.png');
  await control('Operation enabled row-1');
  await waitFor(s=>!s.active&&!s.job.operations[0].enabled,'independent enable toggle');
  if((await state()).job.selectedOperation!=='row-12')throw Error('Enable toggle selected a different operation');
  await control('Undo');await waitFor(s=>!s.active&&s.job.operations[0].enabled,'undo enable');
  await control('Operation row row-12');
  await control('Move earlier');await waitFor(s=>!s.active&&s.job.operations[10].id==='row-12','move earlier from row menu');
  await control('Move later');await waitFor(s=>!s.active&&s.job.operations[11].id==='row-12','move later from row menu');
  await control('Rename');await control('Rename operation');await pressKey('a','KeyA',2);await send('Input.insertText',{text:'Renamed last operation'});
  await control('Apply name');await waitFor(s=>!s.active&&s.job.operations[11].name==='Renamed last operation','rename from row menu');
  await control('Delete operation');await waitFor(s=>!s.active&&s.job.operations.length===11,'delete from row menu');
  await control('Undo');await waitFor(s=>!s.active&&s.job.operations.length===12,'undo row deletion');
  const artwork=(await state()).job.activeArtwork;
  const selected=(await state()).job.selectedOperation;
  await control(`Artwork eye ${artwork}`);await waitFor(s=>s.workspace.hidden_artwork.includes(artwork),'hide display only');
  await control(`Artwork lock ${artwork}`);await waitFor(s=>s.workspace.locked_artwork.includes(artwork),'lock viewport only');
  if((await state()).job.selectedOperation!==selected||(await state()).job.operations.length!==12)throw Error('Artwork state toggles changed operations');
  await control(`Artwork eye ${artwork}`);await control(`Artwork lock ${artwork}`);
  record('twelve ordered operations independent toggles row menus and undo',await state());
  await send('Emulation.setDeviceMetricsOverride',{width:1280,height:800,deviceScaleFactor:2,mobile:false});await sleep(300);
  if(!(await state()).workspace.inspector_collapsed)await control('Toggle inspector');
  if(!(await state()).workspace.navigator_collapsed)await control('Toggle navigator');
  await waitFor(s=>s.workspace.inspector_collapsed&&s.workspace.navigator_collapsed,'both panels collapsed');
  await screenshot('shell-compact-panels-collapsed.png');
  await control('Toggle navigator');await control('Setup');
  await waitFor(s=>!s.workspace.inspector_collapsed&&s.workspace.inspector===1,'setup reopens inspector');
  await screenshot('shell-compact-panels-restored.png');
  record('compact header panel collapse and reopen',await state());
  await send('Emulation.setDeviceMetricsOverride',{width:1440,height:900,deviceScaleFactor:1,mobile:false});await sleep(300);
  const empty=structuredClone(base);empty.name='Empty operation list';empty.operations=[];
  await drop(empty);
  await control('Setup');await control('Machine');
  if(!(await state()).controls['Create or choose machine profile'])throw Error('Empty job lost its machine editor');
  await control('Artwork');
  if(!(await state()).controls['Replace SVG'])throw Error('Empty job lost its artwork source actions');
  await control('Job tools');await waitFor(s=>s.resources.jobsOpen,'empty-job tool access');
  await control('Close job tools');
  await control('Tool library');await waitFor(s=>s.resources.open&&s.resources.ready&&!s.resources.busy,'empty-job library access');
  await control('Close library');
  await screenshot('shell-empty-job.png');
  await control('Add operation');await control('Add Face — face-1');
  await waitFor(s=>!s.active&&s.job.operations.length===1&&s.job.kind==='face','add from empty job');
  if(!isDeepStrictEqual((await state()).job.stock,empty.setup.stock))throw Error('Adding to the empty list changed stock');
  record('zero-operation stock artwork machine and resources remain reachable',await state());
  await drop(base);
  await control('Generation scope');await control('Through selected operation');
  await waitFor(s=>s.current&&!s.active&&s.planScope?.kind==='throughOperation','prefix generation',180);
  if((await state()).planScope.operationId!==base.operations[0].id)throw Error('Prefix scope changed its endpoint');
  await screenshot('shell-prefix-current.png');
  await control('Prepare checked output');await waitFor(s=>s.prepared&&!s.active,'prepare exact retained prefix',180);
  if((await state()).planScope.kind!=='throughOperation')throw Error('Export widened the retained scope');
  record('header prefix generation and checked preparation retain exact scope',await state());
}

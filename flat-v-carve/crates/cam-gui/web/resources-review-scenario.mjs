// V3 acceptance through visible controls in an isolated browser profile.
import {isDeepStrictEqual as same} from 'node:util';
export async function resourcesReviewScenario({control,state,waitFor,send,evaluate,sleep,record,screenshot,readFileSync,chooseFile,pressKey}) {
  const base=JSON.parse(readFileSync('fixtures/gui4/lettering.job.json','utf8'));
  const drop=async job=>{
    await evaluate(`(()=>{const t=new DataTransfer();t.items.add(new File([${JSON.stringify(JSON.stringify(job))}],'resources-review.job.json',{type:'application/json'}));document.getElementById('cam').dispatchEvent(new DragEvent('drop',{dataTransfer:t,bubbles:true,cancelable:true}));})()`);
    await waitFor(s=>s.job?.name===job.name&&s.job.operations.length===job.operations.length&&!s.active,'resource review job');
  };
  const field=async(label,text)=>{await control(label);await pressKey('a','KeyA',2);if(text)await send('Input.insertText',{text});else await pressKey('Backspace','Backspace');await sleep(180);};
  const job=structuredClone(base);
  job.name='Shared cutters across two operations';
  job.operations.push({...structuredClone(job.operations[0]),id:'second-carve',name:'Second carve'});
  await send('Emulation.setDeviceMetricsOverride',{width:1280,height:800,deviceScaleFactor:1,mobile:false});
  await drop(job);
  await control('Operation row second-carve');
  await control('Tool library');await waitFor(s=>s.resources.ready&&!s.resources.busy,'local catalog');
  await chooseFile('Import library','fixtures/gui5/library.json');
  await waitFor(s=>s.resources.dirty&&s.resources.catalog.id==='gui5-lettering-library','imported catalog');
  const before=(await state()).job;
  await field('Library diameter','-');
  await control('Machines');await control('Job tools');await control('Tool library');
  await waitFor(s=>s.resources.page==='ToolLibrary','tool page route');
  if((await state()).resources.raw['endmill/diameter']!=='-'||!same((await state()).job,before))throw Error('Resource routes lost partial geometry or changed the selected job');
  record('routes retain partial library draft and selected operation',await state());
  await field('Library diameter','2.5');
  await control('Library rotation CW');
  await control('Library tool vbit');await control('Library rotation CW');
  await control('Library tool endmill');await control('Library profile rough');
  await control('Save library');await waitFor(s=>!s.resources.busy&&!s.resources.dirty,'saved catalog');
  const draft=(await state()).resources;
  await chooseFile('Import library','fixtures/gui4/broken.svg');
  await waitFor(s=>!s.resources.busy&&s.resources.status!==draft.status,'failed import feedback');
  if(!same((await state()).resources.catalog,draft.catalog)||!same((await state()).resources.raw,draft.raw))throw Error('Failed import destroyed the draft');
  record('failed import retains existing catalog and editing text',await state());
  await screenshot('resources-library-1280.png');
  const layout=(await state()).controls;
  for(const key of ['Library diameter','Profile spindle RPM','Profile stepover']){
    const r=layout[key],v=layout['Resource viewport'];
    if(!r||r[1]<v[1]||r[3]>v[3]+1)throw Error(`${key} is not visible beside the list: ${JSON.stringify({r,v})}`);
  }
  await control('Job tools');await control('Job tool endmill');
  await control('Edit copied geometry');await field('Copied diameter','2.7');await field('Copied shaft diameter','4');await field('Copied stickout','22');
  await control('Apply copied geometry');
  await waitFor(s=>!s.active&&s.job.tools.find(t=>t.id==='endmill').geometry.dimensions.diameter_mm===2.7,'shared geometry apply');
  const edited=(await state()).job.tools.find(t=>t.id==='endmill');
  if(edited.assembly.shaft_diameter_mm!==4||edited.assembly.stickout_mm!==22)throw Error('Geometry apply omitted declared assembly');
  if((await state()).resources.catalog.library.tools[0].geometry.dimensions.diameter_mm!==2.5)throw Error('Copied edit mutated the global catalog');
  await screenshot('resources-job-tools.png');record('shared geometry and declared assembly apply independently of catalog',await state());
  await control('Undo');await waitFor(s=>!s.active&&s.job.tools.find(t=>t.id==='endmill').geometry.dimensions.diameter_mm===2.5,'undo geometry');
  await control('Tool library');await control('Add geometry to job');await waitFor(s=>!s.active&&s.job.tools.length===3,'spare copied geometry');
  const spare=(await state()).job.tools.find(t=>!['endmill','vbit'].includes(t.id)).id;
  await control('Operation row second-carve');await control('Operation Endmill');
  await control('Change endmill tool');
  const beforeUnchanged=(await state()).revision;
  await control('Use selected job tool');await sleep(200);
  if((await state()).revision!==beforeUnchanged||!(await state()).controls['Assignment picker'])throw Error('Reapplying the unchanged job tool cleared cutting values');
  await control('Endmill assignment tool');await control(`Assign endmill ${spare}`);
  const assigned=s=>s.job.profileStatuses.find(a=>a.operationId==='second-carve'&&a.role==='endmill');
  if(assigned(await state()).toolId!=='endmill')throw Error('Choosing a candidate applied before confirmation');
  await screenshot('resources-picker.png');await control('Cancel selection');
  if(assigned(await state()).toolId!=='endmill')throw Error('Cancel changed the assignment');
  await control('Change endmill tool');await control('Endmill assignment tool');await control(`Assign endmill ${spare}`);await control('Use selected job tool');
  await waitFor(s=>!s.active&&assigned(s).toolId===spare,'explicit assignment apply');
  await control('Undo');await waitFor(s=>!s.active&&assigned(s).toolId==='endmill','undo explicit assignment');
  await control('Roughing library tool');await control('Roughing library tool endmill');await control('Roughing library profile');await control('Roughing library profile rough');await control('Apply Roughing library selection');
  await waitFor(s=>!s.active&&assigned(s).status==='applied','selected operation profile');
  if((await state()).job.profileStatuses.find(a=>a.operationId===base.operations[0].id&&a.role==='endmill').status!=='custom')throw Error('Profile application changed the sibling assignment');
  await control(`Operation row ${base.operations[0].id}`);await waitFor(s=>s.job.selectedOperation===base.operations[0].id,'sibling operation');
  if((await state()).job.feed!==1200)throw Error('Profile application altered the sibling cutting feed');
  await control('Operation row second-carve');
  record('focused picker stages candidates cancels safely and applies to one operation',await state());
  await drop(base);await control('Generate');await waitFor(s=>s.current&&!s.active,'playback plan',120);
  await control('Simulate');await control('Start');await control('Play');await sleep(250);
  await control('Tool library');
  const paused=(await state()).display.simulation;
  if(paused.playing)throw Error('Resource entry did not pause playback');
  await sleep(700);
  if((await state()).display.simulation.elapsedSeconds!==paused.elapsedSeconds)throw Error('Resource page advanced the retained playhead');
  await control('Close library');await sleep(500);
  if((await state()).display.simulation.playing||(await state()).display.simulation.elapsedSeconds!==paused.elapsedSeconds)throw Error('Returning resumed playback automatically');
  record('resource route pauses and retains exact playhead without automatic resume',await state());
  await control('Tool library');
  await send('Emulation.setDeviceMetricsOverride',{width:1280,height:800,deviceScaleFactor:2,mobile:false});await sleep(600);
  await screenshot('resources-library-high-dpi.png');
  await control('Machines');await screenshot('resources-machine-high-dpi.png');
  await send('Emulation.setDeviceMetricsOverride',{width:1440,height:900,deviceScaleFactor:1,mobile:false});await sleep(600);
  await screenshot('resources-machines.png');
  record('resource pages at high DPI and standard size',await state());
  await control('Close library');
  await drop(JSON.parse(readFileSync('fixtures/gui6/knife.job.json','utf8')));
  await control('Tool library');await control('New drag knife');
  const knifeTool=(await state()).resources.selectedTool;
  await field('Library blade offset','1');await field('Library cut depth','2');
  await control('New knife profile');
  const knifeProfile=(await state()).resources.selectedProfile;
  await field('Profile cutting feed','210');await field('Profile plunge feed','50');await field('Profile swivel feed','75');await field('Profile stepdown','1');
  await control('Save library');await waitFor(s=>!s.resources.busy&&!s.resources.dirty,'saved knife geometry and profile');
  await screenshot('resources-knife-library.png');
  await control('Close library');await control('Cutting');
  await control('Knife library tool');await control(`Knife library tool ${knifeTool}`);
  await control('Knife library profile');await control(`Knife library profile ${knifeProfile}`);
  await screenshot('resources-knife-picker.png');await control('Apply Knife library selection');
  await waitFor(s=>!s.active&&s.job.knife.assignment.cutting_feed_mm_min===210,'knife focused profile apply');
  record('knife library list details and contextual profile picker',await state());
}
